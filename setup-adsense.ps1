param(
  [Parameter(Mandatory=$true)][ValidatePattern('^ca-pub-\d{16}$')][string]$PublisherId,
  [Parameter(Mandatory=$true)][ValidatePattern('^\d+$')][string]$HomeAfterFinder,
  [Parameter(Mandatory=$true)][ValidatePattern('^\d+$')][string]$HomeBeforeBlog,
  [Parameter(Mandatory=$true)][ValidatePattern('^\d+$')][string]$BlogIndexMiddle,
  [Parameter(Mandatory=$true)][ValidatePattern('^\d+$')][string]$ArticleAfterIntro,
  [Parameter(Mandatory=$true)][ValidatePattern('^\d+$')][string]$ArticleBeforeConclusion
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$configPath = Join-Path $root 'assets\js\adsense-config.js'
$pubNumber = $PublisherId -replace '^ca-pub-', ''
$config = @"
/* Generated by setup-adsense.ps1 */
window.CSC_ADSENSE = Object.freeze({
  enabled: true,
  publisherId: "$PublisherId",
  previewOnLocalhost: true,
  slots: {
    homeAfterFinder: "$HomeAfterFinder",
    homeBeforeBlog: "$HomeBeforeBlog",
    blogIndexMiddle: "$BlogIndexMiddle",
    articleAfterIntro: "$ArticleAfterIntro",
    articleBeforeConclusion: "$ArticleBeforeConclusion"
  }
});
"@

Set-Content -Path $configPath -Value $config -Encoding UTF8
Set-Content -Path (Join-Path $root 'ads.txt') -Value "google.com, pub-$pubNumber, DIRECT, f08c47fec0942fa0" -Encoding ASCII
Write-Host "AdSense configuration enabled successfully." -ForegroundColor Green
Write-Host "Upload the complete folder again, then verify /ads.txt and the website source." -ForegroundColor Cyan
